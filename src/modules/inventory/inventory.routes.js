import { z } from 'zod';
import { objectId } from '@hms/shared/schemas';
import { defineRoutes } from '../../core/http/route.js';
import { withLiveUpdates } from '../../core/realtime/live.js';
import * as inv from './services/inventory.service.js';
import * as stock from './services/stock.service.js';
import * as req from './services/requisition.service.js';

const id = z.object({ id: objectId });
const STOCK_READ = ['inventory:stock:read', 'pharmacy:sale:create'];

/** Inventory (board Inventory): items, stores, stock, POs, GRNs, indents, counts, reports. */
export const inventoryRoutes = defineRoutes({
  module: 'INV',
  basePath: '/inventory',
  routes: withLiveUpdates(
    [
      {
        method: 'get',
        path: '/items',
        permission: ['inventory:item:read', 'inventory:stock:read', 'pharmacy:sale:create'],
        audit: null,
        summary: 'Item master (medicines, consumables, reagents, general)',
        schema: {
          query: z.object({
            q: z.string().trim().max(80).optional(),
            kind: z.enum(['DRUG', 'CONSUMABLE', 'REAGENT', 'GENERAL']).optional(),
          }),
        },
        handler: (req) => inv.listItems(req.valid.query),
      },
      {
        method: 'post',
        path: '/items',
        permission: 'inventory:item:create',
        audit: 'CREATE',
        status: 201,
        summary: 'Add an item (life-saving medicines at 0% GST)',
        schema: { body: inv.itemInput },
        handler: (req) => inv.createItem(req.valid.body),
      },
      {
        method: 'put',
        path: '/items/:id',
        permission: 'inventory:item:update',
        audit: 'UPDATE',
        summary: 'Edit an item (the code stays)',
        schema: { params: id, body: inv.itemInput.partial() },
        handler: (req) => inv.updateItem(req.valid.params.id, req.valid.body),
      },
      {
        method: 'get',
        path: '/stores',
        permission: 'authenticated',
        audit: null,
        summary: 'Stores: main, pharmacy, ward, OT, lab',
        handler: () => inv.listStores(),
      },
      {
        method: 'post',
        path: '/stores',
        permission: 'inventory:settings:update',
        audit: 'CREATE',
        status: 201,
        summary: 'Add a store',
        schema: { body: inv.storeInput },
        handler: (req) => inv.createStore(req.valid.body),
      },
      {
        method: 'get',
        path: '/vendors',
        permission: ['inventory:po:read', 'inventory:grn:create', 'inventory:stock:read'],
        audit: null,
        summary: 'Vendors',
        handler: () => inv.listVendors(),
      },
      {
        method: 'post',
        path: '/vendors',
        permission: ['inventory:po:create', 'inventory:settings:update'],
        audit: 'CREATE',
        status: 201,
        summary: 'Add a vendor (GSTIN checked)',
        schema: { body: inv.vendorInput },
        handler: (req) => inv.createVendor(req.valid.body),
      },
      {
        method: 'get',
        path: '/stock',
        permission: STOCK_READ,
        audit: null,
        summary: 'Stock per item: usable quantity, nearest expiry, value, reorder flag',
        schema: {
          query: z.object({
            storeId: objectId.optional(),
            q: z.string().trim().max(80).optional(),
            kind: z.enum(['DRUG', 'CONSUMABLE', 'REAGENT', 'GENERAL']).optional(),
            low: z.coerce.boolean().optional(),
            page: z.coerce.number().int().min(1).default(1),
            limit: z.coerce.number().int().min(1).max(200).default(100),
          }),
        },
        handler: (req) => stock.stockLevels(req.valid.query),
      },
      {
        method: 'get',
        path: '/items/:id/batches',
        permission: STOCK_READ,
        audit: null,
        summary: 'Batches of an item with expiry and MRP',
        schema: { params: id, query: z.object({ storeId: objectId.optional() }) },
        handler: (req) =>
          stock.itemBatches({ itemId: req.valid.params.id, storeId: req.valid.query.storeId }),
      },
      {
        method: 'get',
        path: '/ledger',
        permission: 'inventory:stock:read',
        audit: null,
        summary: 'Stock ledger (every movement with the balance after it)',
        schema: {
          query: z.object({
            itemId: objectId.optional(),
            storeId: objectId.optional(),
            limit: z.coerce.number().int().min(1).max(500).default(100),
          }),
        },
        handler: (req) => stock.ledger(req.valid.query),
      },
      {
        method: 'get',
        path: '/purchase-orders',
        permission: ['inventory:po:read', 'inventory:po:create', 'inventory:grn:create'],
        audit: null,
        summary: 'Purchase orders',
        schema: { query: z.object({ status: z.string().max(100).optional() }) },
        handler: (req) => inv.listPos(req.valid.query),
      },
      {
        method: 'post',
        path: '/purchase-orders',
        permission: 'inventory:po:create',
        audit: 'CREATE',
        status: 201,
        summary: 'Raise a purchase order (goes for approval)',
        schema: { body: inv.poInput },
        handler: (req, res) => inv.createPo(req.valid.body, res),
      },
      {
        method: 'post',
        path: '/purchase-orders/:id/cancel',
        permission: 'inventory:po:create',
        audit: 'DELETE',
        summary: 'Cancel a purchase order before goods arrive',
        schema: { params: id },
        noBody: true,
        handler: (req) => inv.cancelPo(req.valid.params.id),
      },
      {
        method: 'get',
        path: '/grns',
        permission: ['inventory:grn:create', 'inventory:stock:read'],
        audit: null,
        summary: 'Goods receipts',
        handler: () => inv.listGrns(),
      },
      {
        method: 'post',
        path: '/grns',
        permission: 'inventory:grn:create',
        audit: 'CREATE',
        status: 201,
        summary: 'Receive goods with batch, expiry and MRP (price variance goes for approval)',
        schema: { body: inv.grnInput },
        handler: (req, res) => inv.createGrn(req.valid.body, res),
      },
      {
        method: 'get',
        path: '/indents',
        permission: ['inventory:indent:create', 'inventory:indent:issue', 'inventory:stock:read'],
        audit: null,
        summary: 'Indents from wards and departments',
        schema: { query: z.object({ status: z.string().max(100).optional() }) },
        handler: (req) => inv.listIndents(req.valid.query),
      },
      {
        method: 'post',
        path: '/indents',
        permission: 'inventory:indent:create',
        audit: 'CREATE',
        status: 201,
        summary: 'Raise an indent on a store',
        schema: { body: inv.indentInput },
        handler: (req) => inv.createIndent(req.valid.body),
      },
      {
        method: 'post',
        path: '/indents/:id/issue',
        permission: 'inventory:indent:issue',
        audit: 'UPDATE',
        summary: 'Issue an indent (FEFO transfer; a shortfall stays open)',
        schema: { params: id },
        noBody: true,
        handler: (req) => inv.issueIndent(req.valid.params.id),
      },
      {
        method: 'get',
        path: '/transfers',
        permission: 'inventory:stock:read',
        audit: null,
        summary: 'Store-to-store moves (transfers and indent issues), newest first',
        handler: () => req.listTransfers(),
      },
      {
        method: 'get',
        path: '/requisitions',
        permission: ['inventory:po:read', 'inventory:po:create', 'inventory:indent:create'],
        audit: null,
        summary: 'Purchase requisitions',
        schema: {
          query: z.object({ status: z.enum(['OPEN', 'PO_CREATED', 'REJECTED']).optional() }),
        },
        handler: (r) => req.listRequisitions(r.valid.query),
      },
      {
        method: 'post',
        path: '/requisitions',
        permission: ['inventory:indent:create', 'inventory:po:create'],
        audit: 'CREATE',
        status: 201,
        summary: 'Ask the store to buy items, with the reason',
        schema: { body: req.requisitionInput },
        handler: (r) => req.createRequisition(r.valid.body),
      },
      {
        method: 'post',
        path: '/requisitions/reorder',
        permission: 'inventory:po:create',
        audit: 'CREATE',
        status: 201,
        summary: 'Raise one requisition for every item at or below its reorder level',
        schema: { body: z.object({ storeId: objectId }) },
        handler: (r) => req.fromReorder(r.valid.body),
      },
      {
        method: 'post',
        path: '/requisitions/:id/convert',
        permission: 'inventory:po:create',
        audit: 'UPDATE',
        summary: 'Turn a requisition into a purchase order for a vendor',
        schema: {
          params: z.object({ id: objectId }),
          body: z.object({
            version: z.number().int().min(0),
            vendorId: objectId,
            rates: z.record(z.string(), z.number().int().min(0)).optional(),
          }),
        },
        handler: (r, res) => req.convertToPo(r.valid.params.id, r.valid.body, res),
      },
      {
        method: 'post',
        path: '/requisitions/:id/reject',
        permission: 'inventory:po:create',
        audit: 'UPDATE',
        summary: 'Reject a requisition with the reason',
        schema: {
          params: z.object({ id: objectId }),
          body: z.object({
            version: z.number().int().min(0),
            reason: z.string().trim().min(3).max(300),
          }),
        },
        handler: (r) => req.rejectRequisition(r.valid.params.id, r.valid.body),
      },
      {
        method: 'post',
        path: '/transfers',
        permission: 'inventory:indent:issue',
        audit: 'CREATE',
        status: 201,
        summary: 'Move stock between stores',
        schema: { body: inv.transferInput },
        handler: (req) => inv.directTransfer(req.valid.body),
      },
      {
        method: 'post',
        path: '/adjustments',
        permission: 'inventory:adjust:create',
        audit: 'CREATE',
        status: 201,
        summary: 'Physical count variance (goes for approval)',
        schema: { body: inv.adjustInput },
        handler: (req, res) => inv.createAdjustment(req.valid.body, res),
      },
      {
        method: 'get',
        path: '/reorder',
        permission: ['inventory:po:create', 'inventory:stock:read'],
        audit: null,
        summary: 'Reorder suggestions with the last vendor and rate',
        schema: { query: z.object({ storeId: objectId.optional() }) },
        handler: (req) => inv.reorderSuggestions(req.valid.query),
      },
      {
        method: 'get',
        path: '/reports/expiry',
        permission: ['inventory:stock:read', 'reports:inventory:read'],
        audit: null,
        summary: 'Batches expiring within the days given (and expired)',
        schema: {
          query: z.object({
            days: z.coerce.number().int().min(0).max(365).default(90),
            storeId: objectId.optional(),
          }),
        },
        handler: (req) => stock.expiryReport(req.valid.query),
      },
      {
        method: 'get',
        path: '/reports/dead-stock',
        permission: ['inventory:stock:read', 'reports:inventory:read'],
        audit: null,
        summary: 'Items with stock and no movement out for the days given',
        schema: { query: z.object({ days: z.coerce.number().int().min(30).max(365).default(90) }) },
        handler: (req) => stock.deadStock(req.valid.query),
      },
      {
        method: 'get',
        path: '/settings',
        permission: ['inventory:settings:read', 'inventory:stock:read'],
        audit: null,
        summary: 'Inventory settings',
        handler: () => inv.getSettings(),
      },
      {
        method: 'put',
        path: '/settings',
        permission: 'inventory:settings:update',
        audit: 'UPDATE',
        summary: 'Save inventory settings',
        schema: { body: inv.settingsInput },
        handler: (req) => inv.saveSettings(req.valid.body),
      },
    ],
    'stock:update',
  ),
});
