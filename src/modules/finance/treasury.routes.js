import { z } from 'zod';
import { objectId } from '@hms/shared/schemas';
import { defineRoutes } from '../../core/http/route.js';
import * as assets from './services/assets.service.js';
import * as bank from './services/bankrec.service.js';

const id = z.object({ id: objectId });
const fy = z.string().regex(/^\d{4}-\d{2}$/, 'Use 2026-27');

/** Treasury: bank reconciliation, the fixed asset register and depreciation. */
export const treasuryRoutes = defineRoutes({
  module: 'FIN',
  basePath: '/finance',
  routes: [
    {
      method: 'get',
      path: '/bank/statement',
      permission: ['finance:bank:read', 'finance:report:read'],
      audit: null,
      summary: 'Imported bank statement lines, with match candidates for open lines',
      schema: { query: bank.linesQuery },
      handler: (req) => bank.statementLines(req.valid.query),
    },
    {
      method: 'post',
      path: '/bank/statement',
      permission: 'finance:bank:create',
      audit: 'CREATE',
      summary: 'Import bank statement lines (duplicates skipped) and match automatically',
      schema: { body: bank.importInput },
      handler: (req) => bank.importStatement(req.valid.body),
    },
    {
      method: 'post',
      path: '/bank/auto-match',
      permission: 'finance:bank:create',
      audit: 'UPDATE',
      summary: 'Match open statement lines by amount and date',
      schema: { body: z.object({ accountId: z.string().optional() }) },
      handler: (req) => bank.autoMatch(req.valid.body),
    },
    {
      method: 'post',
      path: '/bank/statement/:id/match',
      permission: 'finance:bank:create',
      audit: 'UPDATE',
      summary: 'Match a statement line to a book entry',
      schema: { params: id, body: bank.matchInput },
      handler: (req) => bank.matchLine(req.valid.params.id, req.valid.body),
    },
    {
      method: 'post',
      path: '/bank/statement/:id/unmatch',
      permission: 'finance:bank:create',
      audit: 'UPDATE',
      summary: 'Undo a match (or restore an ignored line)',
      schema: { params: id, body: bank.versionInput },
      handler: (req) => bank.unmatchLine(req.valid.params.id, req.valid.body),
    },
    {
      method: 'post',
      path: '/bank/statement/:id/ignore',
      permission: 'finance:bank:create',
      audit: 'UPDATE',
      summary: 'Mark a statement line as needing no entry, with a reason',
      schema: { params: id, body: bank.ignoreInput },
      handler: (req) => bank.ignoreLine(req.valid.params.id, req.valid.body),
    },
    {
      method: 'post',
      path: '/bank/statement/:id/book',
      permission: 'finance:bank:create',
      audit: 'CREATE',
      summary: 'Book a bank-only line (charges, interest) and match it',
      schema: { params: id, body: bank.bookInput },
      handler: (req) => bank.bookLine(req.valid.params.id, req.valid.body),
    },
    {
      method: 'get',
      path: '/bank/reconciliation',
      permission: ['finance:bank:read', 'finance:report:read'],
      audit: null,
      summary: 'Bank reconciliation statement as of a date',
      schema: { query: bank.recQuery },
      handler: (req) => bank.reconciliation(req.valid.query),
    },
    {
      method: 'get',
      path: '/assets',
      permission: ['finance:asset:read', 'finance:report:read'],
      audit: null,
      summary: 'Fixed asset register with cost, depreciation and book value',
      schema: { query: z.object({ status: z.enum(['ACTIVE', 'DISPOSED']).optional() }) },
      handler: (req) => assets.listAssets(req.valid.query),
    },
    {
      method: 'get',
      path: '/assets/equipment',
      permission: ['finance:asset:read', 'finance:report:read'],
      audit: null,
      summary: 'Equipment not capitalised yet',
      handler: () => assets.uncapitalisedEquipment(),
    },
    {
      method: 'post',
      path: '/assets',
      permission: 'finance:asset:create',
      audit: 'CREATE',
      status: 201,
      summary: 'Capitalise an asset',
      schema: { body: assets.assetInput },
      handler: (req) => assets.createAsset(req.valid.body),
    },
    {
      method: 'get',
      path: '/assets/depreciation',
      permission: ['finance:asset:read', 'finance:report:read'],
      audit: null,
      summary: 'Depreciation runs',
      handler: () => assets.listRuns(),
    },
    {
      method: 'get',
      path: '/assets/depreciation/preview',
      permission: ['finance:asset:read', 'finance:report:read'],
      audit: null,
      summary: "What a month's depreciation run would charge",
      schema: { query: assets.runInput },
      handler: (req) => assets.previewDepreciation(req.valid.query),
    },
    {
      method: 'post',
      path: '/assets/depreciation',
      permission: 'finance:asset:create',
      audit: 'CREATE',
      summary: "Charge a month's depreciation",
      schema: { body: assets.runInput },
      handler: (req) => assets.runDepreciation(req.valid.body),
    },
    {
      method: 'get',
      path: '/assets/schedule',
      permission: ['finance:asset:read', 'finance:report:read'],
      audit: null,
      summary: 'Schedule of fixed assets for a financial year',
      schema: { query: z.object({ fy }) },
      handler: (req) => assets.schedule(req.valid.query),
    },
    {
      method: 'post',
      path: '/assets/:id/dispose',
      permission: 'finance:asset:update',
      audit: 'UPDATE',
      summary: 'Sell or write off an asset (Finance approves)',
      schema: { params: id, body: assets.disposeInput },
      handler: (req, res) => assets.disposeAsset(req.valid.params.id, req.valid.body, res),
    },
  ],
});
