import { z } from 'zod';
import { objectId } from '@hms/shared/schemas';
import { defineRoutes } from '../../core/http/route.js';
import * as crm from './services/crm.service.js';

const id = z.object({ id: objectId });
const ymd = z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'Use YYYY-MM-DD');
const month = z.string().regex(/^\d{4}-\d{2}$/, 'Use YYYY-MM');
const mobile = z
  .string()
  .trim()
  .regex(/^[6-9]\d{9}$/, 'Enter a 10-digit mobile');
/** Front office and cashiers check membership; the CRM team runs the rest. */
const MEMBER_READ = ['crm:membership:read', 'billing:payment:create', 'opd:appointment:create'];

/** Patient CRM (board Crm): call centre, leads, camps, campaigns, memberships, referrals. */
export const crmRoutes = defineRoutes({
  module: 'CRM',
  basePath: '/crm',
  routes: [
    {
      method: 'get',
      path: '/lookup',
      permission: 'crm:enquiry:read',
      audit: 'VIEW',
      summary: 'Caller lookup by phone: patients, appointments, visits, leads, memberships',
      schema: { query: z.object({ mobile }) },
      handler: (req) => crm.lookup(req.valid.query),
    },
    {
      method: 'post',
      path: '/enquiries',
      permission: 'crm:enquiry:create',
      audit: 'CREATE',
      status: 201,
      summary: 'Log a call or enquiry (optionally opening a lead)',
      schema: { body: crm.enquiryInput },
      handler: (req) => crm.logEnquiry(req.valid.body),
    },
    {
      method: 'get',
      path: '/leads',
      permission: 'crm:lead:read',
      audit: null,
      summary: 'Leads by stage, source, search or follow-ups due',
      schema: {
        query: z.object({
          stage: z.string().max(80).optional(),
          source: z.string().max(20).optional(),
          q: z.string().trim().max(60).optional(),
          due: z.stringbool().optional(),
        }),
      },
      handler: (req) => crm.listLeads(req.valid.query),
    },
    {
      method: 'post',
      path: '/leads',
      permission: 'crm:lead:create',
      audit: 'CREATE',
      status: 201,
      summary: 'Open a lead',
      schema: { body: crm.leadInput },
      handler: (req) => crm.createLead(req.valid.body),
    },
    {
      method: 'patch',
      path: '/leads/:id',
      permission: 'crm:lead:update',
      audit: 'UPDATE',
      summary: 'Stage, note, next follow-up, estimate',
      schema: { params: id, body: crm.leadUpdateInput },
      handler: (req) => crm.updateLead(req.valid.params.id, req.valid.body),
    },
    {
      method: 'get',
      path: '/camps',
      permission: 'crm:camp:read',
      audit: null,
      summary: 'Health camps',
      handler: () => crm.listCamps(),
    },
    {
      method: 'post',
      path: '/camps',
      permission: 'crm:camp:create',
      audit: 'CREATE',
      status: 201,
      summary: 'Plan a health camp',
      schema: { body: crm.campInput },
      handler: (req) => crm.createCamp(req.valid.body),
    },
    {
      method: 'post',
      path: '/camps/:id/registrations',
      permission: 'crm:camp:create',
      audit: 'CREATE',
      summary: 'On-site registration with screening results',
      schema: { params: id, body: crm.registrationInput },
      handler: (req) => crm.registerAtCamp(req.valid.params.id, req.valid.body),
    },
    {
      method: 'post',
      path: '/camps/:id/done',
      permission: 'crm:camp:create',
      audit: 'UPDATE',
      summary: 'Mark the camp held',
      schema: { params: id },
      noBody: true,
      handler: (req) => crm.closeCamp(req.valid.params.id),
    },
    {
      method: 'get',
      path: '/camps/:id/report',
      permission: 'crm:camp:read',
      audit: null,
      summary: 'Camp ROI: registrations, leads, conversions, revenue',
      schema: { params: id },
      handler: (req) => crm.campReport(req.valid.params.id),
    },
    {
      method: 'post',
      path: '/preferences',
      permission: ['crm:campaign:create', 'crm:enquiry:create'],
      audit: 'UPDATE',
      summary: 'Record opt-out (or opt back in) for promotional messages',
      schema: { body: crm.optOutInput },
      handler: (req) => crm.setPreference(req.valid.body),
    },
    {
      method: 'get',
      path: '/campaigns',
      permission: 'crm:campaign:read',
      audit: null,
      summary: 'Campaigns with sent counts and responses',
      handler: () => crm.listCampaigns(),
    },
    {
      method: 'post',
      path: '/campaigns/preview',
      permission: 'crm:campaign:create',
      audit: null,
      summary: 'How many patients the audience reaches (opted-out excluded)',
      schema: { body: crm.campaignInput.shape.audience },
      handler: (req) => crm.previewAudience(req.valid.body),
    },
    {
      method: 'post',
      path: '/campaigns',
      permission: 'crm:campaign:create',
      audit: 'CREATE',
      status: 201,
      summary: 'Draft a campaign',
      schema: { body: crm.campaignInput },
      handler: (req) => crm.createCampaign(req.valid.body),
    },
    {
      method: 'post',
      path: '/campaigns/:id/send',
      permission: 'crm:campaign:send',
      audit: 'UPDATE',
      summary: 'Send the campaign (opt-outs skipped)',
      schema: { params: id },
      noBody: true,
      handler: (req) => crm.sendCampaign(req.valid.params.id),
    },
    {
      method: 'get',
      path: '/plans',
      permission: MEMBER_READ,
      audit: null,
      summary: 'Membership plans',
      handler: () => crm.listPlans(),
    },
    {
      method: 'post',
      path: '/plans',
      permission: 'crm:membership:update',
      audit: 'CREATE',
      status: 201,
      summary: 'Add a membership plan',
      schema: { body: crm.planInput },
      handler: (req) => crm.createPlan(req.valid.body),
    },
    {
      method: 'get',
      path: '/memberships',
      permission: 'crm:membership:read',
      audit: null,
      summary: 'Membership cards (search, renewals due)',
      schema: {
        query: z.object({
          q: z.string().trim().max(60).optional(),
          renewDue: z.stringbool().optional(),
        }),
      },
      handler: (req) => crm.listMemberships(req.valid.query),
    },
    {
      method: 'post',
      path: '/memberships',
      permission: 'crm:membership:create',
      audit: 'CREATE',
      status: 201,
      summary: 'Sell a family health card (fee receipt recorded)',
      schema: { body: crm.membershipInput },
      handler: (req) => crm.sell(req.valid.body),
    },
    {
      method: 'get',
      path: '/members/:id',
      permission: MEMBER_READ,
      audit: null,
      summary: 'The active membership of a patient (id is the patient)',
      schema: { params: id },
      handler: (req) => crm.memberOf(req.valid.params.id),
    },
    {
      method: 'post',
      path: '/memberships/:id/free-visit',
      permission: ['crm:membership:create', 'opd:appointment:create'],
      audit: 'UPDATE',
      summary: 'Use one free consultation',
      schema: {
        params: id,
        body: z.object({ patientId: objectId, ref: z.string().trim().max(40).optional() }),
      },
      handler: (req) => crm.useFreeVisit(req.valid.params.id, req.valid.body),
    },
    {
      method: 'get',
      path: '/referrals',
      permission: 'crm:referral:read',
      audit: null,
      summary: 'Referral partners: patients, visits, revenue and fee for a month',
      schema: { query: z.object({ month }) },
      handler: (req) => crm.referrals(req.valid.query),
    },
    {
      method: 'put',
      path: '/referrals/agreements',
      permission: 'crm:referral:update',
      audit: 'UPDATE',
      summary: 'Referral fee agreement for a source',
      schema: { body: crm.agreementInput },
      handler: (req) => crm.saveAgreement(req.valid.body),
    },
    {
      method: 'post',
      path: '/referrals/statements',
      permission: 'crm:referral:update',
      audit: 'CREATE',
      summary: 'Prepare the month’s referral statements',
      schema: { body: z.object({ month }) },
      handler: (req) => crm.generateStatements(req.valid.body),
    },
    {
      method: 'post',
      path: '/referrals/statements/:id/send',
      permission: 'crm:referral:update',
      audit: 'UPDATE',
      summary: 'Send a statement to Finance',
      schema: { params: id },
      noBody: true,
      handler: (req) => crm.sendStatement(req.valid.params.id),
    },
    {
      method: 'get',
      path: '/report',
      permission: 'crm:report:read',
      audit: null,
      summary: 'Lead funnel, camp conversion, memberships',
      schema: { query: z.object({ from: ymd, to: ymd }) },
      handler: (req) => crm.report(req.valid.query),
    },
  ],
});
