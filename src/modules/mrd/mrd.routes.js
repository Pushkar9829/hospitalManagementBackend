import { z } from 'zod';
import { objectId } from '@hms/shared/schemas';
import { hasPermission } from '@hms/shared';
import { defineRoutes } from '../../core/http/route.js';
import { current } from '../../core/tenancy/context.js';
import * as mrd from './services/mrd.service.js';

const id = z.object({ id: objectId });
const month = z.string().regex(/^\d{4}-\d{2}$/, 'Use YYYY-MM');
const can = (key) => hasPermission([...current().permissions], key);
/** A doctor sees only their own records; MRD staff see all. */
const onlyMine = () => !can('mrd:record:update');

/** Medical records (board Records): completion, coding, files, release, registers, statistics. */
export const mrdRoutes = defineRoutes({
  module: 'MRD',
  basePath: '/mrd',
  routes: [
    {
      method: 'get',
      path: '/records',
      permission: 'mrd:record:read',
      audit: null,
      summary: 'Discharged stays by status (DEFICIENT, CODING, CLOSED) or search',
      schema: {
        query: z.object({
          status: z.string().max(60).optional(),
          q: z.string().trim().max(80).optional(),
          page: z.coerce.number().int().min(1).default(1),
          limit: z.coerce.number().int().min(1).max(200).default(50),
        }),
      },
      handler: (req) => mrd.listRecords({ ...req.valid.query, mine: onlyMine() }),
    },
    {
      method: 'get',
      path: '/records/:id',
      permission: 'mrd:record:read',
      audit: 'VIEW',
      summary: 'A record with its checklist, codes and file movements',
      schema: { params: id },
      handler: (req) => mrd.getRecord(req.valid.params.id),
    },
    {
      method: 'post',
      path: '/records/:id/recheck',
      permission: ['mrd:record:update', 'ipd:note:write'],
      audit: 'UPDATE',
      summary: 'Re-read the stay after notes were completed',
      schema: { params: id },
      noBody: true,
      handler: (req) => mrd.recheck(req.valid.params.id),
    },
    {
      method: 'post',
      path: '/records/:id/resolve',
      permission: 'mrd:record:update',
      audit: 'UPDATE',
      summary: 'Mark a paper item as filed',
      schema: {
        params: id,
        body: z.object({
          code: z.string().trim().max(30),
          note: z.string().trim().min(3).max(200),
        }),
      },
      handler: (req) => mrd.resolveItem(req.valid.params.id, req.valid.body),
    },
    {
      method: 'post',
      path: '/records/:id/coding',
      permission: 'mrd:coding:update',
      audit: 'UPDATE',
      summary: 'Final ICD-10 diagnoses and procedures; closes the record',
      schema: { params: id, body: mrd.codingInput },
      handler: (req) => mrd.code(req.valid.params.id, req.valid.body),
    },
    {
      method: 'post',
      path: '/records/:id/file',
      permission: 'mrd:file:update',
      audit: 'UPDATE',
      summary: 'Register, issue or return the physical file',
      schema: { params: id, body: mrd.fileInput },
      handler: (req) => mrd.fileMove(req.valid.params.id, req.valid.body),
    },
    {
      method: 'get',
      path: '/files/overdue',
      permission: 'mrd:record:read',
      audit: null,
      summary: 'Files out past their due date',
      handler: () => mrd.overdueFiles(),
    },
    {
      method: 'get',
      path: '/deficiencies',
      permission: 'mrd:record:read',
      audit: null,
      summary: 'Open deficiencies by doctor (a doctor sees their own)',
      handler: () => mrd.deficiencies({ mine: onlyMine() }),
    },
    {
      method: 'get',
      path: '/icd10',
      permission: 'mrd:record:read',
      audit: null,
      summary: 'ICD-10 search',
      schema: { query: z.object({ q: z.string().trim().max(60).optional() }) },
      handler: (req) => mrd.icd10(req.valid.query),
    },
    {
      method: 'get',
      path: '/releases',
      permission: 'mrd:release:read',
      audit: null,
      summary: 'Release of information requests',
      schema: { query: z.object({ status: z.string().max(80).optional() }) },
      handler: (req) => mrd.listReleases(req.valid.query),
    },
    {
      method: 'post',
      path: '/releases',
      permission: 'mrd:release:create',
      audit: 'CREATE',
      status: 201,
      summary: 'Request a copy; the Medical Superintendent approves',
      schema: { body: mrd.releaseInput },
      handler: (req, res) => mrd.requestRelease(req.valid.body, res),
    },
    {
      method: 'post',
      path: '/releases/:id/release',
      permission: 'mrd:release:create',
      audit: 'UPDATE',
      summary: 'Hand over the certified copy; the copy fee goes to the cashier',
      schema: { params: id },
      noBody: true,
      handler: (req) => mrd.release(req.valid.params.id),
    },
    {
      method: 'get',
      path: '/births',
      permission: 'mrd:register:read',
      audit: null,
      summary: 'Birth register',
      handler: () => mrd.listBirths(),
    },
    {
      method: 'post',
      path: '/births',
      permission: ['mrd:register:create', 'ipd:note:write'],
      audit: 'CREATE',
      status: 201,
      summary: 'Record a birth (report to CRS within 21 days)',
      schema: { body: mrd.birthInput },
      handler: (req) => mrd.recordBirth(req.valid.body),
    },
    {
      method: 'get',
      path: '/deaths',
      permission: 'mrd:register:read',
      audit: null,
      summary: 'Death register',
      handler: () => mrd.listDeaths(),
    },
    {
      method: 'post',
      path: '/deaths',
      permission: ['mrd:register:create', 'ipd:discharge:update'],
      audit: 'CREATE',
      status: 201,
      summary: 'Record a death with the MCCD',
      schema: { body: mrd.deathInput },
      handler: (req) => mrd.recordDeath(req.valid.body),
    },
    {
      method: 'post',
      path: '/deaths/:id/handover',
      permission: 'mrd:register:create',
      audit: 'UPDATE',
      summary: 'Mortuary: hand over the body with ID proof',
      schema: { params: id, body: mrd.handoverInput },
      handler: (req) => mrd.handover(req.valid.params.id, req.valid.body),
    },
    {
      method: 'post',
      path: '/:kind/:id/reported',
      permission: 'mrd:register:create',
      audit: 'UPDATE',
      summary: 'Mark a birth or death reported to the Civil Registration System',
      schema: {
        params: z.object({ kind: z.enum(['births', 'deaths']), id: objectId }),
        body: z.object({ crsRefNo: z.string().trim().min(3).max(40) }),
      },
      handler: (req) =>
        mrd.markReported(
          req.valid.params.kind === 'births' ? 'birth' : 'death',
          req.valid.params.id,
          req.valid.body,
        ),
    },
    {
      method: 'get',
      path: '/mlc',
      permission: 'mrd:register:read',
      audit: null,
      summary: 'Medico-legal case register',
      handler: () => mrd.listMlc(),
    },
    {
      method: 'post',
      path: '/mlc',
      permission: ['mrd:register:create', 'ipd:note:write'],
      audit: 'CREATE',
      status: 201,
      summary: 'Register a medico-legal case with the police intimation',
      schema: { body: mrd.mlcInput },
      handler: (req) => mrd.recordMlc(req.valid.body),
    },
    {
      method: 'post',
      path: '/mlc/:id/certificate',
      permission: ['mrd:register:create', 'ipd:note:write'],
      audit: 'UPDATE',
      summary: 'Injury certificate issued',
      schema: { params: id },
      noBody: true,
      handler: (req) => mrd.issueInjuryCertificate(req.valid.params.id),
    },
    {
      method: 'get',
      path: '/statistics',
      permission: 'mrd:record:read',
      audit: null,
      summary: 'Monthly hospital statistics',
      schema: { query: z.object({ month }) },
      handler: (req) => mrd.statistics(req.valid.query),
    },
    {
      method: 'get',
      path: '/retention-due',
      permission: 'mrd:record:update',
      audit: null,
      summary: 'Records past their retention period',
      handler: () => mrd.retentionDue(),
    },
  ],
});
